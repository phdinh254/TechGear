-- Nhóm 1 – Tài khoản: người dùng, mã đặt lại mật khẩu, sổ địa chỉ (xem docs/thiet-ke/tu-dien-du-lieu.md)

CREATE TABLE nguoi_dung (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ho_ten           VARCHAR(100) NOT NULL,
    email            VARCHAR(150) NOT NULL,
    mat_khau         VARCHAR(100) NOT NULL,
    so_dien_thoai    VARCHAR(20),
    gioi_tinh        VARCHAR(10)  CHECK (gioi_tinh IN ('nam', 'nu', 'khac')),
    ngay_sinh        DATE,
    anh_dai_dien     VARCHAR(255),
    vai_tro          VARCHAR(20)  NOT NULL DEFAULT 'khach_hang' CHECK (vai_tro IN ('quan_tri', 'khach_hang')),
    trang_thai       VARCHAR(20)  NOT NULL DEFAULT 'hoat_dong' CHECK (trang_thai IN ('hoat_dong', 'bi_khoa')),
    doi_mat_khau_luc TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
-- Email không phân biệt hoa thường
CREATE UNIQUE INDEX uq_nguoi_dung_email ON nguoi_dung (lower(email));

CREATE TABLE ma_dat_lai_mat_khau (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nguoi_dung_id BIGINT      NOT NULL REFERENCES nguoi_dung (id) ON DELETE CASCADE,
    ma_bam        CHAR(64)    NOT NULL UNIQUE,
    het_han_luc   TIMESTAMPTZ NOT NULL,
    da_su_dung    BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_ma_dat_lai_mat_khau_nguoi_dung ON ma_dat_lai_mat_khau (nguoi_dung_id);

CREATE TABLE dia_chi (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nguoi_dung_id    BIGINT       NOT NULL REFERENCES nguoi_dung (id) ON DELETE CASCADE,
    ten_nguoi_nhan   VARCHAR(100) NOT NULL,
    so_dien_thoai    VARCHAR(20)  NOT NULL,
    tinh_thanh       VARCHAR(100) NOT NULL,
    phuong_xa        VARCHAR(100) NOT NULL,
    dia_chi_chi_tiet VARCHAR(255) NOT NULL,
    la_mac_dinh      BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_dia_chi_nguoi_dung ON dia_chi (nguoi_dung_id);
-- Mỗi người tối đa một địa chỉ mặc định
CREATE UNIQUE INDEX uq_dia_chi_mac_dinh ON dia_chi (nguoi_dung_id) WHERE la_mac_dinh;
