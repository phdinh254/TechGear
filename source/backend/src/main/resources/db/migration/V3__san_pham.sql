-- Nhóm 2 – Danh mục, thương hiệu, sản phẩm; Nhóm 3 – banner, cài đặt (xem docs/thiet-ke/tu-dien-du-lieu.md)

CREATE TABLE danh_muc (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    danh_muc_cha_id BIGINT       REFERENCES danh_muc (id),
    ten             VARCHAR(100) NOT NULL,
    slug            VARCHAR(120) NOT NULL,
    mo_ta           TEXT,
    hinh_anh        VARCHAR(255),
    thu_tu          INTEGER      NOT NULL DEFAULT 0,
    hien_thi        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_danh_muc_slug ON danh_muc (slug) WHERE deleted_at IS NULL;
CREATE INDEX ix_danh_muc_cha ON danh_muc (danh_muc_cha_id);

CREATE TABLE thuong_hieu (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ten        VARCHAR(100) NOT NULL,
    slug       VARCHAR(120) NOT NULL,
    logo       VARCHAR(255),
    mo_ta      TEXT,
    hien_thi   BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_thuong_hieu_slug ON thuong_hieu (slug) WHERE deleted_at IS NULL;

CREATE TABLE san_pham (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    danh_muc_id    BIGINT       NOT NULL REFERENCES danh_muc (id),
    thuong_hieu_id BIGINT       REFERENCES thuong_hieu (id),
    ten            VARCHAR(255) NOT NULL,
    slug           VARCHAR(255) NOT NULL,
    mo_ta_ngan     VARCHAR(500),
    mo_ta          TEXT,
    gia_ban        BIGINT       NOT NULL DEFAULT 0 CHECK (gia_ban >= 0),
    gia_goc        BIGINT       CHECK (gia_goc >= 0),
    bao_hanh_thang INTEGER      NOT NULL DEFAULT 0 CHECK (bao_hanh_thang >= 0),
    noi_bat        BOOLEAN      NOT NULL DEFAULT FALSE,
    hien_thi       BOOLEAN      NOT NULL DEFAULT TRUE,
    luot_xem       INTEGER      NOT NULL DEFAULT 0 CHECK (luot_xem >= 0),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at     TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_san_pham_slug ON san_pham (slug) WHERE deleted_at IS NULL;
CREATE INDEX ix_san_pham_danh_muc ON san_pham (danh_muc_id);
CREATE INDEX ix_san_pham_thuong_hieu ON san_pham (thuong_hieu_id);
CREATE INDEX ix_san_pham_gia_ban ON san_pham (gia_ban);

CREATE TABLE thong_so (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id BIGINT       NOT NULL REFERENCES san_pham (id) ON DELETE CASCADE,
    ten         VARCHAR(100) NOT NULL,
    gia_tri     VARCHAR(255) NOT NULL,
    thu_tu      INTEGER      NOT NULL DEFAULT 0
);
CREATE INDEX ix_thong_so_san_pham ON thong_so (san_pham_id);

CREATE TABLE tuy_chon (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id BIGINT      NOT NULL REFERENCES san_pham (id) ON DELETE CASCADE,
    ten         VARCHAR(50) NOT NULL,
    loai        VARCHAR(20) NOT NULL CHECK (loai IN ('mau_sac', 'dung_luong', 'phien_ban', 'khac')),
    thu_tu      INTEGER     NOT NULL DEFAULT 0,
    UNIQUE (san_pham_id, ten)
);

CREATE TABLE gia_tri_tuy_chon (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tuy_chon_id BIGINT      NOT NULL REFERENCES tuy_chon (id) ON DELETE CASCADE,
    gia_tri     VARCHAR(50) NOT NULL,
    ma_mau      CHAR(7)     CHECK (ma_mau ~ '^#[0-9A-Fa-f]{6}$'),
    thu_tu      INTEGER     NOT NULL DEFAULT 0,
    UNIQUE (tuy_chon_id, gia_tri)
);

CREATE TABLE bien_the (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id     BIGINT       NOT NULL REFERENCES san_pham (id),
    sku             VARCHAR(100) NOT NULL,
    gia_ban         BIGINT       NOT NULL CHECK (gia_ban >= 0),
    gia_goc         BIGINT       CHECK (gia_goc IS NULL OR gia_goc >= gia_ban),
    so_luong_ton    INTEGER      NOT NULL DEFAULT 0 CHECK (so_luong_ton >= 0),
    nguong_canh_bao INTEGER      NOT NULL DEFAULT 5 CHECK (nguong_canh_bao >= 0),
    hien_thi        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    deleted_at      TIMESTAMPTZ
);
CREATE UNIQUE INDEX uq_bien_the_sku ON bien_the (sku) WHERE deleted_at IS NULL;
CREATE INDEX ix_bien_the_san_pham ON bien_the (san_pham_id);

CREATE TABLE bien_the_gia_tri (
    bien_the_id         BIGINT NOT NULL REFERENCES bien_the (id) ON DELETE CASCADE,
    gia_tri_tuy_chon_id BIGINT NOT NULL REFERENCES gia_tri_tuy_chon (id) ON DELETE CASCADE,
    PRIMARY KEY (bien_the_id, gia_tri_tuy_chon_id)
);
CREATE INDEX ix_bien_the_gia_tri_gia_tri ON bien_the_gia_tri (gia_tri_tuy_chon_id);

CREATE TABLE hinh_anh_san_pham (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    san_pham_id         BIGINT       NOT NULL REFERENCES san_pham (id) ON DELETE CASCADE,
    gia_tri_tuy_chon_id BIGINT       REFERENCES gia_tri_tuy_chon (id) ON DELETE SET NULL,
    duong_dan           VARCHAR(255) NOT NULL,
    mo_ta               VARCHAR(255),
    thu_tu              INTEGER      NOT NULL DEFAULT 0,
    la_anh_chinh        BOOLEAN      NOT NULL DEFAULT FALSE
);
CREATE INDEX ix_hinh_anh_san_pham ON hinh_anh_san_pham (san_pham_id);
-- Tối đa một ảnh chính mỗi sản phẩm
CREATE UNIQUE INDEX uq_hinh_anh_chinh ON hinh_anh_san_pham (san_pham_id) WHERE la_anh_chinh;

CREATE TABLE banner (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tieu_de      VARCHAR(255),
    hinh_anh     VARCHAR(255) NOT NULL,
    lien_ket     VARCHAR(255),
    thu_tu       INTEGER      NOT NULL DEFAULT 0,
    hien_thi     BOOLEAN      NOT NULL DEFAULT TRUE,
    bat_dau_luc  TIMESTAMPTZ,
    ket_thuc_luc TIMESTAMPTZ,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CHECK (bat_dau_luc IS NULL OR ket_thuc_luc IS NULL OR ket_thuc_luc > bat_dau_luc)
);

